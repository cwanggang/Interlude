export type Strings = (typeof strings)['en'];

export function t(language: Language | undefined): Strings {
  return strings[language ?? 'es'];
}

export function formatDate(ms: number, language: Language, withTime = false): string {
  return new Date(ms).toLocaleString(language === 'es' ? 'es-US' : 'en-US', {
    weekday: 'long',
    month: 'long',
    day: 'numeric',
    ...(withTime ? { hour: 'numeric', minute: '2-digit' } : {}),
  });
}

/** "2026-10-24" → "viernes, 24 de octubre". Parsed as a calendar day, not UTC midnight. */
export function formatDay(day: string, language: Language): string {
  const [y, m, d] = day.split('-').map(Number);
  return new Date(y, m - 1, d).toLocaleDateString(language === 'es' ? 'es-US' : 'en-US', {
    weekday: 'long',
    month: 'long',
    day: 'numeric',
  });
}

/** "6:30 p. m." / "6:30 PM" in the device's time zone. */
export function formatTime(ms: number, language: Language): string {
  return new Date(ms).toLocaleTimeString(language === 'es' ? 'es-US' : 'en-US', { hour: 'numeric', minute: '2-digit' });
}

/** "2026-10-14" → "14 oct" / "Oct 14". */
export function formatShortDay(day: string, language: Language): string {
  const [y, m, d] = day.split('-').map(Number);
  return new Date(y, m - 1, d).toLocaleDateString(language === 'es' ? 'es-US' : 'en-US', { month: 'short', day: 'numeric' });
}
